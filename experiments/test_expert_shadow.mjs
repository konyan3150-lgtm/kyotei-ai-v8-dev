import assert from 'node:assert/strict';
import {allCombinations,adjust,snapshot,settle,evaluate} from './expert_shadow.mjs';
const rows=[1,2,3,4,5,6].map(k=>({k:String(k),p:[.6/k,.4/k,.3/k]}));
const makeBets=rs=>allCombinations(rs).slice(0,6);
const expert={version:2,weights:{inside:.8,upset:0},active:'inside'};
const race={date:'2026-10-03',closed_at:'2026-10-03 12:00:00'};
const params={race,rows,expert,makeBets,date:'20261003',stadium:'1',number:'1',now:new Date('2026-10-03T02:55:00Z')};
const original=structuredClone(rows),all=allCombinations(rows);
assert.equal(all.length,120);assert.equal(new Set(all.map(x=>x.combo)).size,120);
assert.ok(Math.abs(all.reduce((s,x)=>s+x.prob,0)-1)<1e-12);
assert.deepEqual(adjust(rows,{weights:{inside:0,upset:0}}),rows);
assert.ok(adjust(rows,expert)[0].p[0]>rows[0].p[0]);assert.deepEqual(rows,original);
assert.equal(snapshot({...params,now:new Date('2026-10-03T03:00:00Z')}),null);
assert.equal(snapshot({...params,expert:{...expert,reconstructed:true}}),null);
const rec=snapshot({...params,odds:{fetched_at:'2026-10-03T03:01:00Z'}});
assert.equal(rec.odds_snapshot_at,null);assert.equal(rec.baseline_distribution.length,120);
assert.equal(rec.baseline_picks.length,rec.candidate_picks.length);
assert.equal(settle(rec,{combination:'1-1-2',amount:1000}),false);
const actual=rec.baseline_picks[0];assert.ok(settle(rec,{combination:actual,amount:1000}));
assert.equal(settle(rec,{combination:actual,amount:1000}),false);
assert.equal(rec.outcome.metrics.baseline.investment,600);
assert.equal(rec.outcome.metrics.baseline.payout,1000);
const report=evaluate({a:rec});assert.equal(report.settled,1);assert.equal(report.arms.baseline.investment,report.arms.candidate.investment);
assert.throws(()=>allCombinations(rows.slice(1)));
console.log('Expert shadow tests passed: 120 combinations, mass, neutral rule, immutable inputs, time gates and paired stakes.');
